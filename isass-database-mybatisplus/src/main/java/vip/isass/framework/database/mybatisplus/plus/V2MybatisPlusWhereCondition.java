package vip.isass.framework.database.mybatisplus.plus;

import cn.hutool.core.collection.CollUtil;
import cn.hutool.core.util.StrUtil;
import com.baomidou.dynamic.datasource.DynamicRoutingDataSource;
import com.baomidou.mybatisplus.core.conditions.AbstractWrapper;
import com.fasterxml.jackson.core.JsonProcessingException;
import lombok.SneakyThrows;
import org.apache.ibatis.mapping.DatabaseIdProvider;
import vip.isass.framework.common.structure.criteria.V2WhereCondition;
import vip.isass.framework.common.support.JsonUtil;
import vip.isass.framework.common.support.SpringContextUtil;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collection;
import java.util.Collections;
import java.util.List;
import java.util.stream.Collectors;

/**
 * @author Rain
 */
public class V2MybatisPlusWhereCondition {

    @SuppressWarnings("unchecked")
    public static void apply(V2WhereCondition whereCondition, AbstractWrapper wrapper) {
        switch (whereCondition.getCondition()) {
            case OR:
                wrapper.or();
                break;
            case EQUAL:
                wrapper.eq(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case NOT_EQUAL:
                wrapper.ne(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case IN:

                if (whereCondition.getValue() == null) {
                    break;
                }
                if (whereCondition.getValue() instanceof Collection) {
                    wrapper.in(whereCondition.getColumnName(), ((Collection) whereCondition.getValue()).toArray());
                } else {
                    wrapper.in(whereCondition.getColumnName(), whereCondition.getValue());
                }
                break;
            case NOT_IN:
                if (whereCondition.getValue() == null) {
                    break;
                }
                if (whereCondition.getValue() instanceof Collection) {
                    wrapper.notIn(whereCondition.getColumnName(), ((Collection) whereCondition.getValue()).toArray());
                } else {
                    wrapper.notIn(whereCondition.getColumnName(), whereCondition.getValue());
                }
                break;
            case IS_NULL:
                if (StrUtil.isNotBlank(whereCondition.getColumnName())) {
                    wrapper.isNull(whereCondition.getColumnName());
                }
                break;
            case IS_NOT_NULL:
                if (StrUtil.isNotBlank(whereCondition.getColumnName())) {
                    wrapper.isNotNull(whereCondition.getColumnName());
                }
                break;
            case GREATER_THAN:
                wrapper.gt(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case GREATER_THAN_EQUAL:
                wrapper.ge(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case LESS_THAN:
                wrapper.lt(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case LESS_THAN_EQUAL:
                wrapper.le(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case START_WITH:
                wrapper.likeRight(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case LIKE:
                wrapper.like(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case NOT_LIKE:
                wrapper.notLike(whereCondition.getValue() != null, whereCondition.getColumnName(), whereCondition.getValue());
                break;
            case CONTAINS_ALL:
                wrapper.apply(
                        whereCondition.getValue() != null,
                        StrUtil.format("{} @> '{{}}'",
                                whereCondition.getColumnName(),
                                CollUtil.join((Collection) whereCondition.getValue(), ",")));
                break;
            case CONTAINS_ANY:
                wrapper.apply(
                        whereCondition.getValue() != null,
                        StrUtil.format("{} && '{{}}'",
                                whereCondition.getColumnName(),
                                CollUtil.join((Collection) whereCondition.getValue(), ",")));
                break;
            case JSON_OBJECT_PATH_EQUAL:
                if (whereCondition.getValue() == null) {
                    return;
                }
                String[] path = whereCondition.getColumnName().split("\\.", 2);
                path[1] = formatMysqlJsonPath(path[1]);
                switch (getDbType()) {
                    case "":
                    case "mysql":
                        wrapper.apply(
                                StrUtil.format("{}->'$.{}' = {0}", path[0], path[1]),
                                whereCondition.getValue()
                        );
                        break;
                    case "dm":
                        wrapper.like(whereCondition.getValue() != null, path[0], whereCondition.getValue());
                        break;
                }
                break;
            case JSON_OBJECT_PATH_LIKE:
                if (whereCondition.getValue() == null) {
                    return;
                }
                String[] fieldPath = whereCondition.getColumnName().split("\\.", 2);
                fieldPath[1] = formatMysqlJsonPath(fieldPath[1]);
                switch (getDbType()) {
                    case "":
                    case "mysql":
                        wrapper.apply(
                                StrUtil.format("{}->'$.{}' like concat('%',{0},'%')", fieldPath[0], fieldPath[1]),
                                whereCondition.getValue()
                        );
                        break;
                    case "dm":
                        wrapper.like(whereCondition.getValue() != null, fieldPath[0], whereCondition.getValue());
                        break;
                }
                break;
            case JSON_ARRAY_CONTAINS:
                if (whereCondition.getValue() == null) {
                    return;
                }
                switch (getDbType()) {
                    case "":
                    case "mysql":
                        try {
                            wrapper.apply(
                                    StrUtil.format("JSON_CONTAINS({},{0})", whereCondition.getColumnName()),
                                    JsonUtil.DEFAULT_INSTANCE.writeValueAsString(Collections.singletonList(whereCondition.getValue()))
                            );
                        } catch (JsonProcessingException e) {
                            throw new RuntimeException(e);
                        }
                        break;
                    case "dm":
                        wrapper.apply(
                                StrUtil.format("{} like concat('%',{0},'%')", whereCondition.getColumnName()),
                                whereCondition.getValue()
                        );
                        break;
                }

                break;
            case JSON_ARRAY_CONTAINS_ANY:
                Collection<?> containsAnyValues = (Collection<?>) whereCondition.getValue();
                if (CollUtil.isEmpty(containsAnyValues)) {
                    return;
                }
                switch (getDbType()) {
                    case "":
                    case "mysql":
                        try {
                            List<String> sqlFragments = new ArrayList<>(containsAnyValues.size());
                            Object[] valueArr = new Object[containsAnyValues.size()];
                            int i = 0;
                            for (Object o : containsAnyValues) {
                                sqlFragments.add(StrUtil.format("JSON_CONTAINS({},{{}})", whereCondition.getColumnName(), i));
                                valueArr[i] = JsonUtil.DEFAULT_INSTANCE.writeValueAsString(o);
                                i++;
                            }
                            String whereSql = CollUtil.join(sqlFragments, " OR ");
                            wrapper.apply(
                                    whereSql,
                                    valueArr
                            );
                        } catch (JsonProcessingException e) {
                            throw new RuntimeException(e);
                        }
                        break;
                    case "dm":
                        List<String> sqlFragments = new ArrayList<>(containsAnyValues.size());
                        Object[] valueArr = new Object[containsAnyValues.size()];
                        int i = 0;
                        for (Object o : containsAnyValues) {
                            sqlFragments.add(StrUtil.format("{} like concat('%',{{}},'%')", whereCondition.getColumnName(), i));
                            valueArr[i] = o;
                            i++;
                        }
                        String whereSql = CollUtil.join(sqlFragments, " OR ");
                        wrapper.apply(
                                whereSql,
                                valueArr
                        );
                        break;
                }

                break;
            case JSON_ARRAY_CONTAINS_ALL:
                Collection<?> containsAllValues = (Collection<?>) whereCondition.getValue();
                if (CollUtil.isEmpty(containsAllValues)) {
                    return;
                }

                switch (getDbType()) {
                    case "":
                    case "mysql":
                        try {
                            List<String> sqlFragments = new ArrayList<>(containsAllValues.size());
                            Object[] valueArr = new Object[containsAllValues.size()];
                            int i = 0;
                            for (Object o : containsAllValues) {
                                sqlFragments.add(StrUtil.format("JSON_CONTAINS({},{{}})", whereCondition.getColumnName(), i));
                                valueArr[i] = JsonUtil.DEFAULT_INSTANCE.writeValueAsString(o);
                                i++;
                            }
                            String whereSql = CollUtil.join(sqlFragments, " AND ");
                            wrapper.apply(
                                    whereSql,
                                    valueArr
                            );
                        } catch (JsonProcessingException e) {
                            throw new RuntimeException(e);
                        }
                        break;
                    case "dm":
                        List<String> sqlFragments = new ArrayList<>(containsAllValues.size());
                        Object[] valueArr = new Object[containsAllValues.size()];
                        int i = 0;
                        for (Object o : containsAllValues) {
                            sqlFragments.add(StrUtil.format("{} like concat('%',{{}},'%')", whereCondition.getColumnName(), i));
                            valueArr[i] = o;
                            i++;
                        }
                        String whereSql = CollUtil.join(sqlFragments, " AND ");
                        wrapper.apply(
                                whereSql,
                                valueArr
                        );
                        break;
                }

                break;
            default:
                throw new UnsupportedOperationException(StrUtil.format("不支持的[{}]条件转换成mybatis plus wrapper", whereCondition.getCondition()));
        }
    }

    @SneakyThrows
    private static String getDbType() {
        DynamicRoutingDataSource ds = SpringContextUtil.getBean(DynamicRoutingDataSource.class);
        return SpringContextUtil.getBean(DatabaseIdProvider.class)
                .getDatabaseId(ds);
    }

    private static String formatMysqlJsonPath(String jsonPath) {
        if (jsonPath.contains("-")) {
            if (jsonPath.contains(".")) {
                jsonPath = Arrays.stream(jsonPath.split("\\."))
                        .map(p -> p.contains("-") ? StrUtil.format("\"{}\"", p) : p)
                        .collect(Collectors.joining("."));
            } else {
                jsonPath = StrUtil.format("\"{}\"", jsonPath);
            }
        }
        return jsonPath;
    }
}