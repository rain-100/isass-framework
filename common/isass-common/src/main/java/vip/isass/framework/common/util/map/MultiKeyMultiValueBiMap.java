    private Set<?> unmodifiableSet(Set<?> set) {
        return (set == null || set.isEmpty())
                ? Collections.emptySet()
                : Collections.unmodifiableSet(set);
    }

    /**
     * 添加键值对
     * <p>
     * 此方法需在锁内调用，以确保线程安全。
     *
     * @param key   键
     * @param value 值
     */
    private void put0(K key, V value) {
        // 更新正向映射
        keyToValues.computeIfAbsent(key, k -> ConcurrentHashMap.newKeySet()).add(value);

        // 更新反向映射
        valueToKeys.computeIfAbsent(value, v -> ConcurrentHashMap.newKeySet()).add(key);
    }

    /**
     * 批量添加键值对
     * <p>
     * 此方法需在锁内调用，以确保线程安全。
     *
     * @param key       键
     * @param valueIter 肯定有非空值的迭代器
     */
    private void putAll0(K key, Iterator<V> valueIter) {
        Set<V> valueSet = null;
        while (valueIter.hasNext()) {
            V value = valueIter.next();
            if (value == null) {
                continue;
            }
            if (valueSet == null) {
                valueSet = keyToValues.computeIfAbsent(key, k -> ConcurrentHashMap.newKeySet());
            }
            valueSet.add(value);
            valueToKeys.computeIfAbsent(value, v -> ConcurrentHashMap.newKeySet()).add(key);
        }
    }

    /**
     * 设置键的关联值集合并更新反向映射
     * <p>
     * 此方法需在锁内调用，以确保线程安全。
     *
     * @param key 键，调用方需保证不能为 null
     * @return 返回设置后的不可变值集合
     */
    private Set<V> setValuesForKey(K key, Set<V> newValues) {
        if (newValues == null || newValues.isEmpty()) {
            removeKey(key);
            return Collections.emptySet();
        }

        // 将 newValues 转换成 KeySetView 以待添加到映射
        if (!(newValues instanceof ConcurrentHashMap.KeySetView)) {
            Set<V> tempNewValues = newValues;
            newValues = ConcurrentHashMap.newKeySet();
            // 过滤 null 值
            for (V value : tempNewValues) {
                if (value != null) {
                    newValues.add(value);
                }
            }
        }

        // 删除旧的映射
        removeKey(key);

        // 如果新的映射为空，则返回空集合
        if (newValues.isEmpty()) {
            return Collections.emptySet();
        }

        // 添加正向映射
        keyToValues.put(key, newValues);

        // 添加反向映射
        for (V value : newValues) {
            valueToKeys.computeIfAbsent(value, v -> ConcurrentHashMap.newKeySet()).add(key);
        }

        return Collections.unmodifiableSet(newValues);
    }

    /**
     * 设置值的关联键集合并更新正向映射
     * <p>
     * 此方法需在锁内调用，以确保线程安全。
     *
     * @param value 值，调用方需保证不能为 null
     * @return 返回设置后的不可变值集合
     */
    private Set<K> setKeysForValue(V value, Set<K> newKeys) {
        if (newKeys == null || newKeys.isEmpty()) {
            removeValue(value);
            return Collections.emptySet();
        }

        // 将 newKeys 转换成 KeySetView 以待添加到映射
        if (!(newKeys instanceof ConcurrentHashMap.KeySetView)) {
            Set<K> tempNewKeys = newKeys;
            newKeys = ConcurrentHashMap.newKeySet();
            // 过滤 null 值
            for (K key : tempNewKeys) {
                if (key != null) {
                    newKeys.add(key);
                }
            }
        }

        // 删除旧的映射
        removeValue(value);

        // 如果新的集合为空，则返回空集合
        if (newKeys.isEmpty()) {
            return Collections.emptySet();
        }

        // 添加反向映射
        valueToKeys.put(value, newKeys);

        // 添加正向映射
        for (K key : newKeys) {
            keyToValues.computeIfAbsent(key, k -> ConcurrentHashMap.newKeySet()).add(value);
        }

        return Collections.unmodifiableSet(newKeys);
    }

    /**
     * 删除键及其所有关联值
     * <p>
     * 此方法需在锁内调用，以确保线程安全。
     *
     * @param key 要删除的键
     * @return 被删除的值集合
     */
    private Set<V> removeKey0(K key) {
        Set<V> values = keyToValues.remove(key);
        if (values == null || values.isEmpty()) {
            return Collections.emptySet();
        }

        for (V value : values) {
            Set<K> keys = valueToKeys.get(value);
            if (keys == null) {
                continue;
            }
            keys.remove(key);
            if (keys.isEmpty()) {
                valueToKeys.remove(value);
            }
        }
        return Collections.unmodifiableSet(values);
    }

    /**
     * 删除指定的键值对
     * <p>
     * 此方法需在锁内调用，以确保线程安全。
     *
     * @param key   要删除的键
     * @param value 要删除的值
     * @return 是否被删除，如果键值对不存在则返回 false
     */
    private boolean removeKeyValue0(K key, V value) {
        Set<V> valueSet = keyToValues.get(key);
        Set<K> keySet = valueToKeys.get(value);

        if (valueSet == null && keySet == null) {
            return false;
        }

        boolean removed = false;
        if (valueSet != null) {
            removed = valueSet.remove(value);
            if (valueSet.isEmpty()) {
                keyToValues.remove(key);
            }
        }

        if (keySet != null) {
            removed |= keySet.remove(key);
            if (keySet.isEmpty()) {
                valueToKeys.remove(value);
            }
        }

        return removed;
    }

