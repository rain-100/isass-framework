import vip.isass.framework.common.util.map.MultiValueBiMap;
import vip.isass.framework.net.core.message.SendMessageReq;
import vip.isass.framework.net.core.session.DisplaySession;
import vip.isass.framework.net.core.session.Session;
import vip.isass.framework.net.core.session.SessionBindingInfoChangeReq;
import vip.isass.framework.net.core.session.SessionInfoCollection;

import java.util.Collection;
import java.util.Collections;
import java.util.HashSet;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.stream.Collectors;

/**
 * 会话管理器
 * <p>
 * 只提供给 net 模块内部调用。上层应用请使用 INetSessionService
 */
public class NetSessionManager implements INetSessionService {

    public static final NetSessionManager INSTANCE = new NetSessionManager();

    /**
     * 保存所有会话
     * <p> {@literal Map<sessionId, Session>}
     */
    public static final Map<String, Session<?>> sessionMap = new ConcurrentHashMap<>();

    /**
     * 保存用户与会话的映射关系
     * <p> {@literal Map<userId, sessionId>}
     */
    public static final MultiValueBiMap<String, String> userAndSessionMap = new MultiValueBiMap<>();

    /**
     * 保存会话与标签的映射
     * <p> {@literal Map<sessionId, tag>}
     */
    public static final MultiKeyMultiValueBiMap<String, String> sessionAndTagMap = new MultiKeyMultiValueBiMap<>();

    // region session 操作

    public void addSession(Session<?> session) {
        Assert.notNull(session, "session 不能为 null");
        sessionMap.put(session.getSessionId(), session);
    }

    public Session<?> removeSession(Session<?> session) {
        return removeSession(session.getSessionId());
    }

    public Session<?> removeSession(String sessionId) {
        Session<?> remove = sessionMap.remove(sessionId);
        if (remove != null) {
            removeUserId(sessionId);
            removeTags(sessionId);
        }
        return remove;
    }

    public Session<?> getSessionById(String sessionId) {
        return sessionMap.get(sessionId);
    }

    public SessionInfoCollection getSessionInfoCollection() {
        return SessionInfoCollection.builder()
                .sessions(sessionMap.values()
                        .parallelStream()
                        .map(s -> CglibUtil.copy(s, DisplaySession.class))
                        .collect(Collectors.toList()))
                .userAndSessionMap(userAndSessionMap)
                .sessionAndTagMap(sessionAndTagMap)
                .build();
    }

    @EntryPointAnno(name = "保存会话绑定信息", group = "网络会话服务", route = "/${spring.application.name}/session/info", httpMethod = HttpMethod.POST)
    public void saveSessionInfo(@RequestBody SessionBindingInfoChangeReq req) {
        if (StrUtil.isNotBlank(req.getSessionId())) {
            if (StrUtil.isNotBlank(req.getResetUserId())) {
                setUserId(req.getSessionId(), req.getResetUserId());
            } else if (Boolean.TRUE.equals(req.getRemoveUserId())) {
                removeUserId(req.getSessionId());
            }

            if (CollUtil.isNotEmpty(req.getTags())) {
                setTags(req.getSessionId(), req.getTags());
            } else if (Boolean.TRUE.equals(req.getRemoveAllTags())) {
                removeTags(req.getSessionId());
            } else {
                if (CollUtil.isNotEmpty(req.getAddTags())) {
                    addTags(req.getSessionId(), req.getAddTags());
                }
                if (CollUtil.isNotEmpty(req.getRemoveTags())) {
                    removeTags(req.getSessionId(), req.getRemoveTags());
                }
            }
            return;
        }

        Assert.notBlank(req.getUserId(), "sessionId, userId必填其一");
        if (CollUtil.isNotEmpty(req.getTags())) {
            setTagsByUserId(req.getUserId(), req.getTags());
        } else {
            if (CollUtil.isNotEmpty(req.getAddTags())) {
                addTagsByUserId(req.getUserId(), req.getAddTags());
            }
            if (CollUtil.isNotEmpty(req.getRemoveTags())) {
                removeTagsByUserId(req.getUserId(), req.getRemoveTags());
            }

        }
    }

    // endregion

    // region user 操作

    @Override
    public String getUserId(String sessionId) {
        return userAndSessionMap.getKey(sessionId);
    }

    @Override
    public boolean setUserId(String sessionId, String userId) {
        userAndSessionMap.put(userId, sessionId);
        return false;
    }

    public void removeUserId(String sessionId) {
        Assert.notBlank(sessionId, "sessionId 不能为 null 或空字符串");
        userAndSessionMap.removeValue(sessionId);
    }

    @EntryPointAnno(name = "批量判断用户是否在线", group = "网络会话服务", route = "/${spring.application.name}/session/user/isOnline", httpMethod = HttpMethod.POST)
    public Map<String, Boolean> isOnline(Collection<String> userIds) {
        if (userIds == null) {
            return Collections.emptyMap();
        }

        Map<String, Boolean> result = MapUtil.newHashMap(userIds.size());
        for (String userId : userIds) {
            result.put(userId, userAndSessionMap.containsKey(userId));
        }
        return result;
    }

    // endregion

    // region tag 操作

    @Override
    public void addTags(String sessionId, Collection<String> tags) {
        sessionAndTagMap.putAll(sessionId, tags);
    }

    @Override
    public void setTags(String sessionId, Collection<String> tags) {
        sessionAndTagMap.replace(sessionId, tags);
    }

    @Override
    public void removeTags(String sessionId) {
        sessionAndTagMap.removeKey(sessionId);
    }

    @Override
    public void removeTags(String sessionId, Collection<String> removeTags) {
        removeTags.forEach(tag -> sessionAndTagMap.removeKeyValue(sessionId, tag));
    }

    @Override
    public void addTagsByUserId(String userId, Collection<String> tags) {
        Collection<String> sessionIds = userAndSessionMap.get(userId);
        if (CollUtil.isEmpty(sessionIds)) {
            return;
        }
        sessionIds.forEach(s -> addTags(s, tags));
    }

    @Override
    public void setTagsByUserId(String userId, Collection<String> tags) {
        Collection<String> sessionIds = userAndSessionMap.get(userId);
        if (CollUtil.isEmpty(sessionIds)) {
            return;
        }
        sessionIds.forEach(s -> setTags(s, tags));
    }

    @Override
    public void removeTagsByUserId(String userId, Collection<String> tags) {
        Collection<String> sessionIds = userAndSessionMap.get(userId);
        if (CollUtil.isEmpty(sessionIds)) {
            return;
        }
        sessionIds.forEach(s -> removeTags(s, tags));
    }

    // endregion

    // region message

    @Override
    public void broadcastMessage(String cmd, Object payload) {
        sessionMap.entrySet()
                .parallelStream()
                .forEach(entry -> entry.getValue().sendMessage(cmd, payload));
    }

    @Override
    public void sendMessageByUserId(String cmd, Object payload, String userId) {
        Collection<String> sessions = userAndSessionMap.get(userId);
        if (CollUtil.isEmpty(sessions)) {
            return;
        }
        sessions.parallelStream()
                .map(sessionMap::get)
                .forEach(s -> s.sendMessage(cmd, payload));
    }

    @Override
    public void sendMessageByUserIds(String cmd, Object payload, Collection<String> userIds) {
        for (String userId : userIds) {
            sendMessageByUserId(cmd, payload, userId);
        }
    }

    @Override
    public void sendMessageToLoginUsers(String cmd, Object payload) {
        userAndSessionMap.entries()
                .parallelStream()
                .map(Map.Entry::getValue)
                .map(sessionMap::get)
                .forEach(s -> s.sendMessage(cmd, payload));
    }

    @Override
    public void sendMessageByTag(String cmd, Object payload, String tag) {
        Collection<String> sessionIds = sessionAndTagMap.getKeys(tag);
        if (sessionIds == null) {
            return;
        }
        sessionIds.parallelStream()
                .map(sessionMap::get)
                .forEach(s -> s.sendMessage(cmd, payload));
    }

    @Override
    public void sendMessageByTags(String cmd, Object payload, Collection<String> tags) {
        Set<String> sentSessionIds = new HashSet<>();
        for (String tag : tags) {
            Collection<String> sessionIds = sessionAndTagMap.getKeys(tag);
            if (CollUtil.isEmpty(sessionIds)) {
                continue;
            }

            for (String sessionId : sessionIds) {
                if (sentSessionIds.contains(sessionId)) {
                    continue;
                }
                sentSessionIds.add(sessionId);
                Session<?> session = sessionMap.get(sessionId);
                if (session == null) {
                    continue;
                }
                session.sendMessage(cmd, payload);
            }
        }
    }

    @Override
    public void sendMessageByAnyTags(String cmd, Object payload, Collection<String> tags) {
        Map<String, Boolean> sentSessionIds = new ConcurrentHashMap<>();
        for (String tag : tags) {
            Collection<String> sessionIds = sessionAndTagMap.getKeys(tag);
            if (sessionIds == null) {
                continue;
            }

            sessionIds.parallelStream()
                    .filter(s -> sentSessionIds.putIfAbsent(s, Boolean.TRUE) == null)
                    .map(sessionMap::get)
                    .forEach(s -> s.sendMessage(cmd, payload));
        }
    }

    /**
     * 发送消息
     *
     * @param sendMessageReq 消息
     */
    @Override
    @EntryPointAnno(name = "发送消息给客户端", group = "网络会话服务", route = "/${spring.application.name}/session/send", httpMethod = HttpMethod.POST)
    public void sendMessage(@RequestBody SendMessageReq sendMessageReq) {
        Assert.notNull(sendMessageReq, "消息不能为空");

        // 1：判断 receiverSession 和 receiverSessionId
        if (sendMessageReq.getReceiverSession() != null) {
            sendMessageReq.getReceiverSession().sendMessage(sendMessageReq.getEvent(), sendMessageReq.getPayload());
            return;
        }
        if (StrUtil.isNotBlank(sendMessageReq.getReceiverSessionId())) {
            Session<?> session = sessionMap.get(sendMessageReq.getReceiverSessionId());
            if (session == null) {
                return;
            }
            session.sendMessage(sendMessageReq.getEvent(), sendMessageReq.getPayload());
            return;
        }

        // 2：判断 userId
        Set<String> finalSessionIds = null;
        boolean modifiable = false; // finalSessionIds 是否可修改的集合
        if (CollUtil.isNotEmpty(sendMessageReq.getUserIds())) {
            for (String userId : sendMessageReq.getUserIds()) {
                Collection<String> sessionIdsFromUserId = userAndSessionMap.get(userId);
                if (CollUtil.isEmpty(sessionIdsFromUserId)) {
                    continue;
                }
                if (finalSessionIds == null) {
                    if (sessionIdsFromUserId instanceof Set) {
                        finalSessionIds = (Set<String>) sessionIdsFromUserId;
                    } else {
                        finalSessionIds = new HashSet<>(sessionIdsFromUserId);
                        modifiable = true;
                    }
                } else {
                    if (modifiable) {
                        finalSessionIds.addAll(sessionIdsFromUserId);
                    } else {
                        finalSessionIds = new HashSet<>(finalSessionIds);
                        modifiable = true;
                    }
                }
            }

            if (finalSessionIds == null) {
                return;
            }
        }

        // 4：叠加判断 tags
        if (CollUtil.isNotEmpty(sendMessageReq.getTags())) {
            for (String tag : sendMessageReq.getTags()) {
                Set<String> sessionIdsFromTag = sessionAndTagMap.getKeys(tag);
                if (CollUtil.isEmpty(sessionIdsFromTag)) {
                    return;
                }

                // 如果上一步根据用户id找到了sessionId，则判断此步找到的sessionId是否被上一步的包含
                if (finalSessionIds == null) {
                    finalSessionIds = new HashSet<>(sessionIdsFromTag);
                    modifiable = true;
                } else {
                    if (!modifiable) {
                        finalSessionIds = new HashSet<>(finalSessionIds);
                        modifiable = true;
                    }
                    finalSessionIds.retainAll(sessionIdsFromTag);
                    if (finalSessionIds.isEmpty()) {
                        return;
                    }
                }
            }

            // 因为设置了 tags，所以无需再判断 tagsAny，如果 finalSessionIds 非空，则给这些会话发送消息
            if (CollUtil.isNotEmpty(finalSessionIds)) {
                finalSessionIds.parallelStream()
                        .map(sessionMap::get)
                        .filter(Objects::nonNull)
                        .forEach(s -> s.sendMessage(sendMessageReq.getEvent(), sendMessageReq.getPayload()));
            }
            return;
        }

        // 5：叠加判断 tagsAny
        if (CollUtil.isNotEmpty(sendMessageReq.getTagsAny())) {
            Set<String> sentSessionIds = ConcurrentHashMap.newKeySet();
            for (String tag : sendMessageReq.getTagsAny()) {
                Set<String> sessionIdsFromTag = sessionAndTagMap.getKeys(tag);
                if (CollUtil.isEmpty(sessionIdsFromTag)) {
                    continue;
                }

                if (CollUtil.isEmpty(finalSessionIds)) {
                    sessionIdsFromTag.parallelStream()
                            .filter(sentSessionIds::add)
                            .map(sessionMap::get)
                            .filter(Objects::nonNull)
                            .forEach(s -> s.sendMessage(sendMessageReq.getEvent(), sendMessageReq.getPayload()));
                } else {
                    Collection<String> firstColl;
                    Collection<String> secondColl;
                    if (sessionIdsFromTag.size() > finalSessionIds.size()) {
                        firstColl = finalSessionIds;
                        secondColl = sessionIdsFromTag;
                    } else {
                        firstColl = sessionIdsFromTag;
                        secondColl = finalSessionIds;
                    }
                    for (String loopSessionId : firstColl) {
                        if (secondColl.contains(loopSessionId) && sentSessionIds.add(loopSessionId)) {
                            Session<?> session = sessionMap.get(loopSessionId);
                            if (session != null) {
                                session.sendMessage(sendMessageReq.getEvent(), sendMessageReq.getPayload());
                            }
                        }
                    }
                }
            }
            return;
        }


        // 6：最后方法依然没 return，则广播或者发消息给 finalSessionIds
        if (finalSessionIds == null) {
            broadcastMessage(sendMessageReq.getEvent(), sendMessageReq.getPayload());
        } else {
            finalSessionIds.parallelStream()
                    .map(sessionMap::get)
                    .filter(Objects::nonNull)
                    .forEach(s -> s.sendMessage(sendMessageReq.getEvent(), sendMessageReq.getPayload()));
        }
    }

    @EntryPointAnno(name = "批量发送消息给客户端", group = "网络会话服务", route = "/${spring.application.name}/session/send/batch", httpMethod = HttpMethod.POST)
    public void sendMessages(@RequestBody Collection<SendMessageReq> sendMessageReqs) {
        sendMessageReqs.parallelStream().forEach(this::sendMessage);
    }

    // endregion

}
